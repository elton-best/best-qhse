function RootShell({ children }: { children: ReactNode }) {
  return (
    <I18nProvider>
      <LocalizedDocument>{children}</LocalizedDocument>
    </I18nProvider>
  );
}

function LocalizedDocument({ children }: { children: ReactNode }) {
  const { locale } = useI18n();
  return (
    <html lang={locale}>
      <head>
        <HeadContent />
      </head>
      <body>
        {children}
        <Scripts />
      </body>
    </html>
  );
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();
  const router = useRouter();

  useEffect(() => {
    const onAuthChanged = () => {
      router.invalidate();
      queryClient.invalidateQueries();
    };
    window.addEventListener("lq-auth-changed", onAuthChanged);
    return () => window.removeEventListener("lq-auth-changed", onAuthChanged);
  }, [queryClient, router]);

  return (
    <QueryClientProvider client={queryClient}>
      {/* Required: nested routes render here. Removing <Outlet /> breaks all child routes. */}
      <Outlet />
      <Toaster position="top-center" richColors />
    </QueryClientProvider>
  );
}
